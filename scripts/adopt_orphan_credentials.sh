#!/usr/bin/env bash
# Seal the credentials that live only in the cluster, so git describes them.
#
# WHAT THIS CLOSES. scripts/secrets_gate.py reports a credential declared
# store=sealed that no SealedSecret owns. Six of those are hand-made Secrets
# that predate this platform's GitOps, and one of them, airflow-s3-credentials,
# is why remote task logging was dead for four days: a rotation invalidated a
# credential nothing described, and nothing could report it.
#
# VALUE NEUTRAL BY CONSTRUCTION. Every secret here is sealed from the value it
# already holds, so no consumer sees a change and nothing needs restarting. The
# script proves that by comparing a hash of every key before and after, and
# refuses to leave a manifest behind if any key differs.
#
# THE ONE THAT WOULD HURT. airflow-fernet-key encrypts every connection stored
# in Airflow's metadata database. A wrong value there does not fail loudly, it
# makes existing connections undecryptable. That is why this script never
# generates a value and dies on any mismatch.
#
# ADOPTION. The sealed-secrets controller refuses to overwrite a Secret it does
# not own. The annotation has to be on the EXISTING Secret for the takeover,
# because the SealedSecret template is only what the controller writes after it
# has decided it may write at all.
#
# Idempotent. A second run re-seals the same values and reports no change.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
MF=platform-gitops/manifests
CREDS=platform-gitops/credentials

k(){ kubectl --context sentpul "$@"; }
# kubeseal fetches the sealing certificate from the controller, so it needs the
# same context. Sealing against the wrong cluster fails invisibly.
seal_stdin(){ kubeseal --context sentpul --format yaml; }

C_G=$'\e[32m'; C_Y=$'\e[33m'; C_0=$'\e[0m'
ok(){ printf '  %s✓%s %s\n' "$C_G" "$C_0" "$*"; }
warn(){ printf '  %s!%s %s\n' "$C_Y" "$C_0" "$*"; }
die(){ printf '\n%sFAILED:%s %s\n' $'\e[31m' "$C_0" "$*" >&2; exit 1; }

for t in kubectl kubeseal; do command -v $t >/dev/null || die "missing tool: $t"; done
k get nodes >/dev/null 2>&1 || die "kube context 'sentpul' unreachable"

d="$(mktemp -d)"; trap 'rm -rf "$d"' EXIT; umask 077

# Every credential the gate reports as declared-sealed and owned by nothing.
# Listed explicitly rather than discovered, so adding one is a visible edit and
# a surprise in the cluster cannot silently pull a new secret into git.
TARGETS="
airflow/airflow-fernet-key
airflow/airflow-git-credentials
airflow/airflow-sso-credentials
airflow/airflow-webserver-secret
kube-system/cloudflared-creds
webapp/ghcr-pull
"

adopt(){ # <namespace> <name>
  local ns="$1" name="$2"
  local out="$MF/adopted-${ns}-${name}-sealed-secret.yaml"

  k -n "$ns" get secret "$name" >/dev/null 2>&1 || { warn "$ns/$name does not exist, skipping"; return 0; }

  local owner
  owner="$(k -n "$ns" get secret "$name" -o jsonpath='{.metadata.ownerReferences[0].kind}' 2>/dev/null || true)"
  if [ "$owner" = SealedSecret ]; then
    ok "$ns/$name is already owned by a SealedSecret, nothing to do"
    return 0
  fi

  # The type matters. ghcr-pull is kubernetes.io/dockerconfigjson, and recreating
  # it as Opaque would leave a Secret that kubelet cannot use as a pull secret.
  local stype
  stype="$(k -n "$ns" get secret "$name" -o jsonpath='{.type}')"

  # Every key, by name, read into files so no value reaches argv.
  local keys key args=()
  keys="$(k -n "$ns" get secret "$name" -o go-template='{{range $k,$v := .data}}{{$k}}{{"\n"}}{{end}}')"
  [ -n "$keys" ] || die "$ns/$name has no data"
  : > "$d/before.sha"
  while read -r key; do
    [ -z "$key" ] && continue
    # go-template with index, NOT jsonpath. A key can begin with a dot:
    # ghcr-pull's is ".dockerconfigjson", and jsonpath={.data..dockerconfigjson}
    # parses as a recursive descent and returns the wrong bytes. That produced a
    # SealedSecret the controller rejected as invalid JSON.
    k -n "$ns" get secret "$name" \
      -o go-template="{{index .data \"$key\" | base64decode}}" > "$d/$key"
    printf '%s %s\n' "$key" "$(sha256sum < "$d/$key" | cut -d' ' -f1)" >> "$d/before.sha"
    args+=( --from-file="$key=$d/$key" )
  done <<< "$keys"

  # Permit the takeover on the live Secret, then seal with the annotation in the
  # template too so adoption survives the Secret being recreated from git.
  k -n "$ns" annotate secret "$name" sealedsecrets.bitnami.com/managed=true --overwrite >/dev/null

  k create secret generic "$name" -n "$ns" --type="$stype" "${args[@]}" --dry-run=client -o yaml \
    | k annotate --local -f - sealedsecrets.bitnami.com/managed=true -o yaml \
    | seal_stdin > "$d/s.yaml"
  grep -q 'kind: SealedSecret' "$d/s.yaml" || die "kubeseal produced no SealedSecret for $ns/$name"

  { echo "# Generated by scripts/adopt_orphan_credentials.sh on $(date -Is)."
    echo "# Sealed from the value $ns/$name already held, so no consumer sees a"
    echo "# change. Ciphertext is safe to commit: only the in-cluster"
    echo "# sealed-secrets controller holds the private key."
    echo "#"
    echo "# managed: \"true\" is load bearing. It is what let the controller adopt"
    echo "# a Secret that predates this manifest."
    grep -v '^\s*creationTimestamp' "$d/s.yaml"; } > "$out"
  k apply -f "$out" >/dev/null

  local i
  for i in $(seq 1 30); do
    [ "$(k -n "$ns" get secret "$name" -o jsonpath='{.metadata.ownerReferences[0].kind}' 2>/dev/null)" = SealedSecret ] && break
    sleep 1
  done
  [ "$(k -n "$ns" get secret "$name" -o jsonpath='{.metadata.ownerReferences[0].kind}')" = SealedSecret ] \
    || die "the controller did not adopt $ns/$name, do NOT commit $out"

  # Every key, byte for byte. A fernet key that changed would not fail loudly.
  while read -r key want; do
    local got
    got="$(k -n "$ns" get secret "$name" \
             -o go-template="{{index .data \"$key\" | base64decode}}" | sha256sum | cut -d' ' -f1)"
    [ "$want" = "$got" ] || die "$ns/$name key $key CHANGED, do NOT commit $out"
  done < "$d/before.sha"

  local ntype
  ntype="$(k -n "$ns" get secret "$name" -o jsonpath='{.type}')"
  [ "$ntype" = "$stype" ] || die "$ns/$name type became $ntype, was $stype, do NOT commit $out"

  ok "$ns/$name: adopted, $(wc -l < "$d/before.sha") key(s) unchanged, type $stype -> $out"
}

for t in $TARGETS; do
  adopt "${t%%/*}" "${t##*/}"
done

echo
printf '%sNow commit the generated manifests under %s and merge, or ArgoCD never owns them.%s\n' "$C_Y" "$MF" "$C_0"
printf '%sThe three Applications that serve them are already in platform-gitops/apps/.%s\n' "$C_Y" "$C_0"
echo
echo "Then confirm the gate: python scripts/secrets_gate.py"
echo "Declarations already exist in $CREDS for all six, so no new file is needed."
