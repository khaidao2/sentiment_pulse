#!/usr/bin/env bash
# Reconcile the ClickHouse CONSUMER secrets with the password the ClickHouse
# server actually runs on.
#
# WHY THIS EXISTS. A ClickHouse rotation has two halves: the server's own
# password (sealed into database/clickhouse-server-sealed, read by the
# Deployment) and the copies its consumers read -- airflow/clickhouse-credentials
# for the KPO task pods and dbt, and airflow/grafana-clickhouse-ds-sealed for
# Grafana's datasource. fix_remaining_platform_security.sh rotated the server
# but left both consumer blobs on the old value, so every DAG task and every
# Grafana ClickHouse panel failed authentication while the manifests looked
# clean and ArgoCD reported Synced.
#
# So this script never invents a password. It reads the live server secret and
# seals THAT, which makes drift impossible by construction: there is one source
# of truth and the consumers are derived from it.
#
# Run it after any ClickHouse server rotation, or any time a consumer is
# suspected of having drifted -- it is idempotent and safe to repeat.
#
# ORDERING. The sealed secrets are applied here so the fix takes effect at once,
# but clickhouse-credentials is an ArgoCD Application with selfHeal=true: the
# applied value is reverted to git within minutes. COMMIT AND MERGE the two
# regenerated manifests, or this undoes itself.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
MF=platform-gitops/manifests
k(){ kubectl --context sentpul "$@"; }
C_G=$'\e[32m'; C_Y=$'\e[33m'; C_0=$'\e[0m'
ok(){ printf '  %s✓%s %s\n' "$C_G" "$C_0" "$*"; }
die(){ printf '\n%sFAILED:%s %s\n' $'\e[31m' "$C_0" "$*" >&2; exit 1; }

for t in kubectl kubeseal openssl; do command -v $t >/dev/null || die "missing tool: $t"; done
k get nodes >/dev/null 2>&1 || die "kube context 'sentpul' unreachable"

d="$(mktemp -d)"; trap 'rm -rf "$d"' EXIT; umask 077

# The one source of truth.
k -n database get secret clickhouse-server-sealed -o jsonpath='{.data.CLICKHOUSE_PASSWORD}' \
  | base64 -d > "$d/pw"
[ -s "$d/pw" ] || die "database/clickhouse-server-sealed holds no CLICKHOUSE_PASSWORD"
ok "read the live server password ($(wc -c < "$d/pw") bytes, sha $(sha256sum < "$d/pw" | cut -c1-10))"

CH_USER="$(grep -A1 'name: CLICKHOUSE_USER' "$MF/clickhouse.yaml" | sed -nE 's/.*value: "?([^"]*)"?/\1/p' | head -1)"
CH_USER="${CH_USER:-clickhouse}"

reseal(){ # <ns> <secret> <key> <out.yaml>
  local ns="$1" name="$2" key="$3" out="$4"
  cp "$d/pw" "$d/$key"
  k create secret generic "$name" -n "$ns" --from-file="$key=$d/$key" --dry-run=client -o yaml \
    | kubeseal --format yaml > "$d/s.yaml"
  { echo "# Generated by scripts/reseal_clickhouse_consumers.sh on $(date -Is)."
    echo "# Sealed from the live value of database/clickhouse-server-sealed, so the"
    echo "# server and its consumers cannot drift apart. Never edit by hand: the"
    echo "# ciphertext is the only copy and re-running the script is the way to change it."
    grep -v '^\s*creationTimestamp' "$d/s.yaml"; } > "$out"
  k apply -f "$out" >/dev/null
  local i; for i in $(seq 1 30); do k -n "$ns" get secret "$name" >/dev/null 2>&1 && break; sleep 1; done
  k -n "$ns" get secret "$name" >/dev/null 2>&1 || die "$ns/$name never materialised -- do NOT commit $out"

  # Prove it: authenticate against the server with the value the consumer now
  # holds. A sealed secret that materialises is not the same as one that works.
  local pod; pod="$(k -n database get pods -l app=clickhouse -o jsonpath='{.items[0].metadata.name}')"
  k -n "$ns" get secret "$name" -o jsonpath="{.data.$key}" | base64 -d \
    | k -n database exec -i "$pod" -- sh -c \
        "IFS= read -r p; clickhouse-client --user $CH_USER --password \"\$p\" -q 'SELECT 1'" \
        >/dev/null 2>&1 \
    || die "$ns/$name does not authenticate against the server -- do NOT commit $out"
  ok "sealed, applied and authenticated: $ns/$name ($key)"
}

reseal airflow clickhouse-credentials       password               "$MF/clickhouse-sealed-credentials.yaml"
reseal airflow grafana-clickhouse-ds-sealed CH_DATASOURCE_PASSWORD "$MF/grafana-clickhouse-ds-sealed-secret.yaml"

# Grafana reads CH_DATASOURCE_PASSWORD through envFromSecrets, so it only sees a
# new value after a restart. Airflow's KPO task pods read theirs per task run.
k -n airflow rollout restart deploy/grafana >/dev/null 2>&1 \
  && k -n airflow rollout status deploy/grafana --timeout=180s >/dev/null 2>&1 \
  && ok "grafana restarted (envFromSecrets is read at boot)" \
  || printf '  %s!%s grafana restart did not complete; restart it by hand\n' "$C_Y" "$C_0"

printf '\n%sNow commit and merge both manifests, or ArgoCD selfHeal reverts them.%s\n' "$C_Y" "$C_0"
