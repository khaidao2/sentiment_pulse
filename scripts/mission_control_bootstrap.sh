#!/usr/bin/env bash
# mission_control_bootstrap.sh - create the stateful things Mission Control needs
# before it can run, and seal every credential it creates.
#
# WHAT IT MAKES.
#   1. A PostgreSQL role and database of its own in the shared instance in ns
#      database. Mission Control does NOT share the web app's database. Its nine
#      tables would otherwise land beside the web app's jobs schema, under the
#      web app's credentials, and a restore of one product would roll back the
#      other.
#   2. A MinIO bucket, plus the FIRST non-root MinIO identity on this platform,
#      scoped by policy to that one bucket. Today MinIO has no users and no
#      service accounts, so every client authenticates as root. Giving a new
#      application root was not worth doing twice.
#   3. SealedSecret manifests for both credentials, so the gate in
#      scripts/secrets_gate.py can account for them.
#
# WHAT IT DOES NOT DO. It creates nothing on GitHub and publishes no hostname.
# Those steps are listed at the end for you to run, because they are outward
# facing or need a token only you can mint.
#
# Idempotent. Run it twice and the second run reports what already exists.
#
# Usage:
#   ./scripts/mission_control_bootstrap.sh
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
MF=platform-gitops/manifests
NS=mission-control
BUCKET=mission-control
PG_DB=mission_control
PG_USER=mission_control
INV=platform-gitops/secrets-inventory.tsv

k(){ kubectl --context sentpul "$@"; }
seal_stdin(){ kubeseal --context sentpul --format yaml; }
C_G=$'\e[32m'; C_Y=$'\e[33m'; C_0=$'\e[0m'
ok(){ printf '  %s✓%s %s\n' "$C_G" "$C_0" "$*"; }
warn(){ printf '  %s!%s %s\n' "$C_Y" "$C_0" "$*"; }
die(){ printf '\n%sFAILED:%s %s\n' $'\e[31m' "$C_0" "$*" >&2; exit 1; }
strong(){ openssl rand -base64 36 | tr -d '\n=+/' | cut -c1-32; }

for t in kubectl kubeseal openssl; do command -v $t >/dev/null || die "missing tool: $t"; done
k get nodes >/dev/null 2>&1 || die "kube context 'sentpul' unreachable"
k get ns "$NS" >/dev/null 2>&1 || die "namespace $NS does not exist. Merge the mission-control Application first."

d="$(mktemp -d)"; trap 'rm -rf "$d"' EXIT; umask 077

# ------------------------------------------------------------------ postgres --
PG_POD=postgres-postgresql-0
k -n database get pod "$PG_POD" >/dev/null 2>&1 || die "$PG_POD not found in ns database"

# The instance's own superuser password, read from the secret the chart made.
k -n database get secret postgres-postgresql -o jsonpath='{.data.postgres-password}' \
  | base64 -d > "$d/pgsuper"
[ -s "$d/pgsuper" ] || die "could not read the postgres superuser password"

psql_super(){ # reads SQL on stdin
  k -n database exec -i "$PG_POD" -- env PGPASSWORD="$(cat "$d/pgsuper")" \
    psql -U postgres -v ON_ERROR_STOP=1 -q
}

if printf 'SELECT 1 FROM pg_roles WHERE rolname = %s;\n' "'$PG_USER'" \
    | psql_super -tA 2>/dev/null | grep -q 1; then
  ok "postgres role $PG_USER already exists, leaving its password alone"
  PG_PASS=""
else
  PG_PASS="$(strong)"
  printf "CREATE ROLE %s LOGIN PASSWORD '%s';\n" "$PG_USER" "$PG_PASS" | psql_super \
    || die "could not create the $PG_USER role"
  ok "created the postgres role $PG_USER"
fi

if printf 'SELECT 1 FROM pg_database WHERE datname = %s;\n' "'$PG_DB'" \
    | psql_super -tA 2>/dev/null | grep -q 1; then
  ok "database $PG_DB already exists"
else
  printf 'CREATE DATABASE %s OWNER %s;\n' "$PG_DB" "$PG_USER" | psql_super \
    || die "could not create the $PG_DB database"
  ok "created the database $PG_DB owned by $PG_USER"
fi

if [ -n "$PG_PASS" ]; then
  # The DSN, not the parts. The application reads one value, so one value is
  # what gets sealed, and nothing has to reassemble it correctly at runtime.
  printf 'postgresql://%s:%s@postgres-postgresql.database.svc.cluster.local:5432/%s' \
    "$PG_USER" "$PG_PASS" "$PG_DB" > "$d/dsn"
  k create secret generic mission-control-postgres-credentials -n "$NS" \
      --from-file="dsn=$d/dsn" --dry-run=client -o yaml \
    | seal_stdin > "$d/pg.yaml"
  { echo "# Generated by scripts/mission_control_bootstrap.sh on $(date -Is)."
    echo "# Mission Control's own database in the shared postgres instance, not"
    echo "# the web app's. Re-running the script does not rotate this; it leaves"
    echo "# an existing role's password alone."
    grep -v '^\s*creationTimestamp' "$d/pg.yaml"; } \
    > "$MF/mission-control-postgres-sealed-secret.yaml"
  k apply -f "$MF/mission-control-postgres-sealed-secret.yaml" >/dev/null
  ok "sealed and applied $NS/mission-control-postgres-credentials"
else
  warn "role existed, so no DSN was sealed. Delete the role and re-run to rotate it."
fi

# --------------------------------------------------------------------- minio --
MINIO_POD="$(k -n database get pods -l app=minio -o jsonpath='{.items[0].metadata.name}')"
[ -n "$MINIO_POD" ] || die "no running MinIO pod in ns database"

MC_AK="mission-control"
MC_SK="$(strong)"

cat > "$d/policy.json" <<JSON
{
  "Version": "2012-10-17",
  "Statement": [
    {
      "Effect": "Allow",
      "Action": ["s3:ListBucket", "s3:GetBucketLocation"],
      "Resource": ["arn:aws:s3:::$BUCKET"]
    },
    {
      "Effect": "Allow",
      "Action": ["s3:GetObject", "s3:PutObject", "s3:DeleteObject", "s3:AbortMultipartUpload", "s3:ListMultipartUploadParts"],
      "Resource": ["arn:aws:s3:::$BUCKET/*"]
    }
  ]
}
JSON

# Root credentials come from the pod's own env, so they never reach this
# machine's argv or a file here.
minio_do(){ # reads a script on stdin, runs it in the MinIO pod with mc configured
  k -n database exec -i "$MINIO_POD" -- sh -c '
    export MC_HOST_loc="http://$MINIO_ROOT_USER:$MINIO_ROOT_PASSWORD@127.0.0.1:9000"
    sh -s'
}

printf 'mc mb --ignore-existing loc/%s >/dev/null && echo bucket-ok\n' "$BUCKET" \
  | minio_do | grep -q bucket-ok && ok "bucket $BUCKET exists" || die "could not create the bucket"

# `mc admin policy create` on current MinIO, `add` on older builds. Trying both
# is cheaper than pinning a version this script does not control.
{ printf 'cat > /tmp/p.json <<%s\n' 'EOFP'; cat "$d/policy.json"; printf 'EOFP\n'
  printf 'mc admin policy create loc %s-rw /tmp/p.json >/dev/null 2>&1 || mc admin policy add loc %s-rw /tmp/p.json >/dev/null 2>&1 || true\n' "$BUCKET" "$BUCKET"
  printf 'rm -f /tmp/p.json\n'
  printf 'echo policy-done\n'; } | minio_do | grep -q policy-done \
  && ok "policy ${BUCKET}-rw written, scoped to that one bucket"

if printf 'mc admin user info loc %s >/dev/null 2>&1 && echo exists\n' "$MC_AK" | minio_do | grep -q exists; then
  warn "minio user $MC_AK already exists, so no new key was sealed"
  MC_SK=""
else
  printf 'mc admin user add loc %s %s >/dev/null && mc admin policy attach loc %s-rw --user %s >/dev/null 2>&1 || mc admin policy set loc %s-rw user=%s >/dev/null 2>&1; echo user-done\n' \
    "$MC_AK" "$MC_SK" "$BUCKET" "$MC_AK" "$BUCKET" "$MC_AK" | minio_do | grep -q user-done \
    || die "could not create the minio user"
  ok "created the minio user $MC_AK with only ${BUCKET}-rw"
fi

if [ -n "$MC_SK" ]; then
  printf %s "$MC_AK" > "$d/ak"; printf %s "$MC_SK" > "$d/sk"
  printf %s "http://minio.database.svc.cluster.local:9000" > "$d/endpoint"
  printf %s "$BUCKET" > "$d/bucket"
  k create secret generic mission-control-s3-credentials -n "$NS" \
      --from-file="access_key=$d/ak" --from-file="secret_key=$d/sk" \
      --from-file="endpoint=$d/endpoint" --from-file="bucket=$d/bucket" \
      --dry-run=client -o yaml | seal_stdin > "$d/s3.yaml"
  { echo "# Generated by scripts/mission_control_bootstrap.sh on $(date -Is)."
    echo "# The first non-root MinIO identity on this platform, scoped by the"
    echo "# ${BUCKET}-rw policy to one bucket. Every other MinIO client here"
    echo "# still authenticates as root, which is tracked separately."
    grep -v '^\s*creationTimestamp' "$d/s3.yaml"; } \
    > "$MF/mission-control-s3-sealed-secret.yaml"
  k apply -f "$MF/mission-control-s3-sealed-secret.yaml" >/dev/null
  ok "sealed and applied $NS/mission-control-s3-credentials"
fi

# Prove the new identity actually works, rather than trusting that it was made.
if [ -n "$MC_SK" ]; then
  printf 'export MC_HOST_app="http://%s:%s@127.0.0.1:9000"; mc ls app/%s >/dev/null 2>&1 && echo auth-ok\n' \
      "$MC_AK" "$MC_SK" "$BUCKET" \
    | k -n database exec -i "$MINIO_POD" -- sh -s | grep -q auth-ok \
    && ok "the $MC_AK identity authenticates and can read its bucket" \
    || die "the $MC_AK identity does not work, do NOT commit its manifest"
fi

# ------------------------------------------------------------------ hand back --
echo
printf '%sStill yours to do, because these need GitHub or a browser:%s\n' "$C_Y" "$C_0"
cat <<'NEXT'

  1. A deploy key so CD can pin the image sha into this repo.
     The web app already has one on this repo, and a GitHub deploy key cannot be
     reused across repositories, so this has to be a new key.

       ssh-keygen -t ed25519 -N '' -C 'mission-control CD pin' -f ~/.ssh/mc_gitops
       gh repo deploy-key add ~/.ssh/mc_gitops.pub --repo khaidao2/sentiment_pulse \
         --title 'mission-control CD pin' --allow-write
       gh secret set GITOPS_SSH_KEY --repo khaidao2/mission-control < ~/.ssh/mc_gitops
       shred -u ~/.ssh/mc_gitops ~/.ssh/mc_gitops.pub

  2. A registry pull credential, because ghcr.io/khaidao2/* answers 401, so the
     packages are private. Mint a classic PAT with ONLY read:packages at
     https://github.com/settings/tokens/new?scopes=read:packages then:

       kubectl --context sentpul create secret docker-registry ghcr-pull \
         -n mission-control --docker-server=ghcr.io \
         --docker-username=khaidao2 --docker-password='<the PAT>' \
         --dry-run=client -o yaml \
         | kubeseal --context sentpul --format yaml \
         > platform-gitops/manifests/mission-control-ghcr-pull-sealed-secret.yaml

     The webapp namespace has a hand-made ghcr-pull that is not in git. Sealing
     this one keeps the new namespace off that path.

  3. The Keycloak client:

       ./scripts/mission_control_keycloak.sh

     then seal the secret it prints, as that script instructs.

  4. Add one inventory row per credential you sealed, or
     scripts/secrets_gate.py fails on a credential with no declared store:

       mission-control	mission-control-postgres-credentials	rotatable	sealed
       mission-control	mission-control-s3-credentials	persistent	sealed
       mission-control	mission-control-oidc	persistent	sealed
       mission-control	ghcr-pull	persistent	sealed

  5. Commit every generated manifest under platform-gitops/manifests/, or
     ArgoCD selfHeal will revert what this script applied.
NEXT
