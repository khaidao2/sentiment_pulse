#!/usr/bin/env bash
# mlflow_dev_keycloak.sh - create the Keycloak client for mlflow-dev.sentpul.click.
#
# MLflow has no login of its own, so oauth2-proxy is its public access boundary.
# This script updates Keycloak, seals the proxy credentials into git-ready files,
# and stores the allowed email only in the cluster because this repository is public.
#
# Usage:
#   MLFLOW_ALLOWED_EMAIL=you@example.com ./scripts/mlflow_dev_keycloak.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=scripts/keycloak_common.sh
source "${SCRIPT_DIR}/keycloak_common.sh"
cd "${SCRIPT_DIR}/.."

NS=mlops-dev
URL=https://mlflow-dev.sentpul.click
SECRET_NAME=oauth2-proxy-mlflow-dev-sealed
OUT=platform-gitops/manifests/mlflow-dev-oauth2-proxy-sealed-secret.yaml
DECL="platform-gitops/credentials/${NS}.${SECRET_NAME}.yaml"

[[ "${MLFLOW_ALLOWED_EMAIL:-}" =~ ^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$ ]] \
  || die "Set MLFLOW_ALLOWED_EMAIL to the one address allowed to sign in."
command -v kubeseal >/dev/null || die "kubeseal is required."

_d="$(mktemp -d)"
trap 'rm -rf "$_d"; _kc_cleanup' EXIT
umask 077
openssl rand -base64 36 | tr -d '\n=+/' | cut -c1-32 | tr -d '\n' > "$_d/client-secret"
openssl rand -base64 32 | tr -- '+/' '-_' | tr -d '\n' > "$_d/cookie-secret"
printf %s mlflow-dev > "$_d/client-id"

# Seal first, so a sealing failure cannot leave Keycloak on an undelivered secret.
kubectl --context "$KC_KUBE_CONTEXT" create secret generic "$SECRET_NAME" -n "$NS" \
    --from-file="client-id=$_d/client-id" \
    --from-file="client-secret=$_d/client-secret" \
    --from-file="cookie-secret=$_d/cookie-secret" --dry-run=client -o yaml \
  | kubeseal --context "$KC_KUBE_CONTEXT" --format yaml > "$_d/sealed.yaml"
grep -q 'kind: SealedSecret' "$_d/sealed.yaml" || die "kubeseal produced no SealedSecret"

kc_init
kc_upsert_client "$(jq -n --rawfile s "$_d/client-secret" --arg u "$URL" '{
  clientId:                  "mlflow-dev",
  name:                      "MLflow Dev",
  description:               "Credit MLOps dev model registry",
  enabled:                   true,
  protocol:                  "openid-connect",
  publicClient:              false,
  clientAuthenticatorType:   "client-secret",
  secret:                    $s,
  standardFlowEnabled:       true,
  implicitFlowEnabled:       false,
  directAccessGrantsEnabled: false,
  serviceAccountsEnabled:    false,
  redirectUris:              [($u + "/oauth2/callback")],
  webOrigins:                [$u],
  attributes: {
    "pkce.code.challenge.method": "S256",
    "post.logout.redirect.uris":  ($u + "/*")
  }
}')"

{ echo "# Generated by scripts/mlflow_dev_keycloak.sh."
  echo "# Credentials for the oauth2-proxy that gates mlflow-dev.sentpul.click."
  grep -v '^\s*creationTimestamp' "$_d/sealed.yaml"; } > "$OUT"
{ echo "namespace: $NS"
  echo "name: $SECRET_NAME"
  echo "class: persistent"
  echo "store: sealed"
  echo 'reason: ""'; } > "$DECL"

kubectl --context "$KC_KUBE_CONTEXT" create configmap oauth2-proxy-allowed-emails -n "$NS" \
    --from-literal="restricted_user_access=${MLFLOW_ALLOWED_EMAIL}" --dry-run=client -o yaml \
  | kubectl --context "$KC_KUBE_CONTEXT" apply -f - >/dev/null

ok "Keycloak client, sealed secret, declaration and allowlist are ready."
