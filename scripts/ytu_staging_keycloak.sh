#!/usr/bin/env bash
# ytu_staging_keycloak.sh - the Keycloak side of ytu-staging.sentpul.click (KAN-27).
#
# Creates or updates the `ytu-staging` OIDC client that the oauth2-proxy sidecar in
# the YTU agent pod signs people in with, and the approver realm roles the approval
# API routes to. Seals the client secret and a fresh cookie secret into
# platform-gitops/manifests/ytu-staging-oauth2-proxy-sealed-secret.yaml.
#
# Nothing is applied to the cluster here: Argo CD applies the sealed file after merge,
# because selfHeal reverts a hand-applied SealedSecret to the git ciphertext.
#
# Usage:
#   ./scripts/ytu_staging_keycloak.sh
#   YTU_TEST_USER=ytu-team ./scripts/ytu_staging_keycloak.sh   # also grant the roles
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/keycloak_common.sh"
cd "${SCRIPT_DIR}/.."

YTU_URL="${YTU_STAGING_URL:-https://ytu-staging.sentpul.click}"
YTU_NS=ytu-staging
OUT=platform-gitops/manifests/ytu-staging-oauth2-proxy-sealed-secret.yaml
ROLES=(warehouse_lead cs_lead finance)

command -v kubeseal >/dev/null || die "kubeseal is required to seal the client secret."
kubectl --context "$KC_KUBE_CONTEXT" get ns "$YTU_NS" >/dev/null 2>&1 \
  || die "namespace $YTU_NS does not exist on context $KC_KUBE_CONTEXT."

_d="$(mktemp -d)"; umask 077
trap '_kc_cleanup; rm -rf "$_d"' EXIT
openssl rand -base64 48 | tr -d '\n=+/' | cut -c1-32 | tr -d '\n' > "$_d/client-secret"
# oauth2-proxy needs a 16, 24 or 32 byte cookie secret.
openssl rand -hex 16 | tr -d '\n' > "$_d/cookie-secret"

kc_init
kc_upsert_client "$(jq -n --rawfile s "$_d/client-secret" --arg u "$YTU_URL" '{
  clientId:                  "ytu-staging",
  name:                      "YTU Ops staging",
  enabled:                   true,
  protocol:                  "openid-connect",
  publicClient:              false,
  clientAuthenticatorType:   "client-secret",
  secret:                    $s,
  standardFlowEnabled:       true,
  implicitFlowEnabled:       false,
  directAccessGrantsEnabled: false,
  serviceAccountsEnabled:    false,
  redirectUris:              [($u + "/oauth2/callback")],
  webOrigins:                [$u],
  attributes: {
    "pkce.code.challenge.method": "S256",
    "post.logout.redirect.uris":  ($u + "/*")
  },
  protocolMappers: [
    {
      name:            "audience",
      protocol:        "openid-connect",
      protocolMapper:  "oidc-audience-mapper",
      consentRequired: false,
      config: {
        "included.client.audience": "ytu-staging",
        "id.token.claim":           "true",
        "access.token.claim":       "true"
      }
    }
  ]
}')"

kc_upsert_realm_role warehouse_lead "YTU Ops: approves held warehouse fulfilment steps"
kc_upsert_realm_role cs_lead        "YTU Ops: approves held customer service steps"
kc_upsert_realm_role finance        "YTU Ops: approves refunds and other money steps"

if [[ -n "${YTU_TEST_USER:-}" ]]; then
  uid="$(curl -sf -H "Authorization: Bearer $TOKEN" \
    "${KC_URL}/admin/realms/${REALM_NAME}/users?username=${YTU_TEST_USER}&exact=true" \
    | jq -r '.[0].id // empty')"
  [[ -n "$uid" ]] || die "user ${YTU_TEST_USER} not found in ${REALM_NAME}."
  roles_json="$(for r in "${ROLES[@]}"; do
    curl -sf -H "Authorization: Bearer $TOKEN" "${KC_URL}/admin/realms/${REALM_NAME}/roles/${r}"
  done | jq -s '[.[] | {id, name}]')"
  curl -sf -X POST -H "Authorization: Bearer $TOKEN" -H "Content-Type: application/json" \
    --data-binary "$roles_json" \
    "${KC_URL}/admin/realms/${REALM_NAME}/users/${uid}/role-mappings/realm" \
    || die "granting approver roles to ${YTU_TEST_USER} failed."
  ok "Granted ${ROLES[*]} to ${YTU_TEST_USER}."
fi

kubectl --context "$KC_KUBE_CONTEXT" create secret generic oauth2-proxy-ytu -n "$YTU_NS" \
    --from-file=client-secret="$_d/client-secret" \
    --from-file=cookie-secret="$_d/cookie-secret" --dry-run=client -o yaml \
  | kubeseal --context "$KC_KUBE_CONTEXT" --format yaml > "$_d/sealed.yaml"
grep -q 'kind: SealedSecret' "$_d/sealed.yaml" || die "kubeseal produced no SealedSecret"
{ echo "# Generated by scripts/ytu_staging_keycloak.sh on $(date -Is)."
  echo "# Client secret of the ytu-staging Keycloak client and the oauth2-proxy cookie"
  echo "# secret. To roll both, re-run the script and merge the new file."
  grep -v '^\s*creationTimestamp' "$_d/sealed.yaml"; } > "$OUT"
ok "Wrote $OUT. Commit and merge it; Argo CD applies it."
