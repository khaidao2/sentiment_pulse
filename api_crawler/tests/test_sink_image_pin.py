"""`sent-gen render` must not revert the production image pin.

The sink Deployments are generated from `contracts/streaming/*_sink.yaml`, whose
`workload.image` is the floating `ghcr.io/.../sentiment-pulse-crawler:latest`.
CD (.github/workflows/build-image.yml) then seds those generated manifests to
the immutable `sha-<sha>` tag and commits it ("chore(cd): pin sinks to sha-...",
e.g. 834ad99 and 9a11100) so ArgoCD sees a manifest change and rolls the new
build out. Git therefore holds a tag the contract does not know about, and a
plain re-render used to overwrite it with `:latest` -- silently rolling
production back to whatever `:latest` happens to point at, with no diff in any
contract to explain it.

`_preserve_pinned_image()` closes that: a `sha-` pin already in the manifest for
the same repository survives regeneration. Everything else still comes from the
contract -- no manifest yet, a different repository, or a non-pin tag all fall
back to it -- so the file stays a function of the contract plus exactly one
CD-owned fact, and the line-1 AUTO-GENERATED banner stays true.

The last test is the same "committed state is current" guard
test_topic_reconcile_contract.py applies to the reconciler's ConfigMap.
"""

from pathlib import Path

import pytest

from sentpul.cli import _preserve_pinned_image, _render_contract, _streaming_context
from sentpul.contract import iter_contracts
from sentpul.renderer import render_template

_ROOT = Path(__file__).resolve().parents[2]
_CONTRACTS = _ROOT / "data-contracts" / "contracts"
_IMAGE = "ghcr.io/khaidao2/sentiment-pulse-crawler"
_PIN = "sha-99ffbb2"


def _manifest(tmp_path: Path, image: str) -> Path:
    """A minimal rendered-looking manifest carrying `image`."""
    path = tmp_path / "topcv_sink.yaml"
    path.write_text(
        "# AUTO-GENERATED by sent-gen — DO NOT EDIT. Edit the contract instead.\n"
        "spec:\n"
        "  template:\n"
        "    spec:\n"
        "      containers:\n"
        "        - name: topcv-sink\n"
        f"          image: {image}\n"
        "          imagePullPolicy: Always\n",
        encoding="utf-8",
    )
    return path


@pytest.fixture(scope="module")
def sink_contracts() -> list:
    """Every streaming contract -- these are the ones CD pins."""
    contracts = [c for c in iter_contracts(_CONTRACTS) if c.kind == "streaming"]
    assert contracts, "no streaming contracts found -- fixture exercises nothing"
    return contracts


# ── the pin survives ──────────────────────────────────────────────────────


def test_existing_sha_pin_is_preserved(tmp_path):
    """The bug: regenerating over a CD-written pin must keep that pin."""
    path = _manifest(tmp_path, f"{_IMAGE}:{_PIN}")
    assert _preserve_pinned_image(f"{_IMAGE}:latest", path) == f"{_IMAGE}:{_PIN}"


def test_missing_manifest_falls_back_to_the_contract(tmp_path):
    """A brand new contract has no manifest yet -- use the contract's image."""
    path = tmp_path / "does_not_exist.yaml"
    assert not path.exists()
    assert _preserve_pinned_image(f"{_IMAGE}:latest", path) == f"{_IMAGE}:latest"


def test_non_pin_tags_are_not_preserved(tmp_path):
    """Only `sha-` pins are CD's. Anything else must not outlive the contract."""
    for tag in ("latest", "v2.1", "sha-nothex", "sha-abc"):
        path = _manifest(tmp_path, f"{_IMAGE}:{tag}")
        assert _preserve_pinned_image(f"{_IMAGE}:latest", path) == f"{_IMAGE}:latest"


def test_a_repointed_contract_wins_over_the_old_pin(tmp_path):
    """Changing `workload.image` to another repository must take effect.

    Otherwise the preservation rule would quietly veto a deliberate edit.
    """
    path = _manifest(tmp_path, f"{_IMAGE}:{_PIN}")
    other = "ghcr.io/khaidao2/other-image:latest"
    assert _preserve_pinned_image(other, path) == other


def test_an_untagged_contract_image_still_gets_the_pin(tmp_path):
    """An untagged contract image means implicit `:latest` on the same repo.

    Same repository, same floating meaning -- so the pin still wins.
    """
    path = _manifest(tmp_path, f"{_IMAGE}:{_PIN}")
    assert _preserve_pinned_image(_IMAGE, path) == f"{_IMAGE}:{_PIN}"


def test_a_registry_port_is_not_read_as_a_tag(tmp_path):
    """`host:5000/img` has a port, not a tag -- the repo must survive intact."""
    ported = "registry.internal:5000/sentiment-pulse-crawler"
    path = _manifest(tmp_path, f"{ported}:{_PIN}")
    assert _preserve_pinned_image(f"{ported}:latest", path) == f"{ported}:{_PIN}"
    assert _preserve_pinned_image(f"{_IMAGE}:latest", path) == f"{_IMAGE}:latest"


def test_streaming_context_carries_the_pin(sink_contracts):
    """The preservation runs in the real render path, not just the helper."""
    for c in sink_contracts:
        rendered = c.manifest_path.read_text(encoding="utf-8")
        if f"{_IMAGE}:sha-" not in rendered:
            continue  # not currently pinned -- nothing to preserve
        expected = rendered.split("image: ", 1)[1].split("\n", 1)[0]
        assert _streaming_context(c)["image"] == expected


# ── render stays idempotent, committed state stays current ────────────────


def test_two_consecutive_renders_are_byte_identical(sink_contracts, tmp_path):
    """Rendering twice over its own output must produce the same bytes."""
    for c in sink_contracts:
        path = tmp_path / f"{c.name}.yaml"
        for image in (f"{_IMAGE}:latest", f"{_IMAGE}:{_PIN}"):
            ctx = _streaming_context(c)
            ctx["image"] = _preserve_pinned_image(image, path)
            first = render_template("k8s_deployment.yaml.jinja", **ctx)
            path.write_text(first, encoding="utf-8")

            ctx = _streaming_context(c)
            ctx["image"] = _preserve_pinned_image(image, path)
            second = render_template("k8s_deployment.yaml.jinja", **ctx)
            assert second == first, f"{c.name}: second render differs"
            # And the pin is what came back out, not the floating tag.
            if image.endswith(_PIN):
                assert f"{_IMAGE}:{_PIN}" in second


def test_committed_sink_manifests_match_generator_output(sink_contracts):
    """Every real sink manifest must be exactly what `sent-gen render` emits.

    Catches a stale manifest (a contract changed and nobody re-rendered) and a
    hand-edit of an AUTO-GENERATED file.
    """
    for c in sink_contracts:
        expected = render_template("k8s_deployment.yaml.jinja", **_streaming_context(c))
        actual = c.manifest_path.read_text(encoding="utf-8")
        assert actual == expected, (
            f"{c.manifest_path} differs from `sent-gen render` output -- "
            "run `sent-gen render`")


def test_render_does_not_touch_the_pinned_manifests(sink_contracts):
    """A full `_render_contract()` pass must leave the pinned files byte-equal.

    This is the end-to-end form of the bug: it writes the real files, exactly
    as the CLI does, and asserts nothing moved.
    """
    paths = [p for c in sink_contracts
             for p in (c.manifest_path, c.app_path, c.sql_path) if p.exists()]
    before = {p: p.read_bytes() for p in paths}
    try:
        for c in sink_contracts:
            _render_contract(c, dry_run=False)
        after = {p: p.read_bytes() for p in paths}
    finally:
        # Never leave the working tree dirty, even when the assertion below fails.
        for path, content in before.items():
            path.write_bytes(content)
    for path, content in before.items():
        assert after[path] == content, f"{path} was rewritten by render"


def test_generated_manifests_still_say_they_are_generated(sink_contracts):
    for c in sink_contracts:
        head = c.manifest_path.read_text(encoding="utf-8").splitlines()[0]
        assert "AUTO-GENERATED by sent-gen" in head, (
            "the repo convention is that generated manifests say so on line 1")
